import { readFileSync, writeFileSync } from "node:fs";
import { globSync } from "node:fs";

const CLASS = /\.(-?[_a-zA-Z][\w-]*)/g;

const camel = (name) =>
  name
    .split("-")
    .map((part, i) => (i === 0 ? part : part[0].toUpperCase() + part.slice(1)))
    .join("");

/**
 * Declares each stylesheet's exact class names, so a typo at a call site fails typecheck
 * rather than silently rendering an unstyled element.
 */
for (const file of globSync("src/**/*.module.css")) {
  const css = readFileSync(file, "utf8").replace(/\/\*[\s\S]*?\*\//g, "");
  const names = [...new Set([...css.matchAll(CLASS)].map((m) => camel(m[1])))].sort();
  const body = names.map((n) => `  readonly ${n}: string;`).join("\n");
  writeFileSync(
    `${file}.d.ts`,
    `// Generated by scripts/css-module-types.mjs. Run \`npm run styles:types\` after editing the stylesheet.\ndeclare const styles: {\n${body}\n};\nexport default styles;\n`,
  );
}
